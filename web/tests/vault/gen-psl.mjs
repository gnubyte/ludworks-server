// Generates web/assets/js/lib/vault/psl-data.js — the pinned Public Suffix List snapshot used for
// `domain` URI matching (VAULT-CRYPTO.md §3.1) — from a local public_suffix_list.dat:
//
//   node web/tests/vault/gen-psl.mjs <path/to/public_suffix_list.dat> <YYYY-MM-DD snapshot date> --write
//
// Source: https://publicsuffix.org/list/public_suffix_list.dat (Ubuntu/Debian ship a copy in the
// `publicsuffix` package at /usr/share/publicsuffix/public_suffix_list.dat). Clients never fetch the list
// at runtime: they embed this snapshot so every client computes the same registrable domains.
//
// Normalisation (other clients that generate their own copy must apply the same rules):
//  * both the ICANN and the PRIVATE sections are kept (github.io, duckdns.org, ts.net, ... are private);
//  * comments and blank lines are dropped, each rule is the first whitespace-delimited token of its line;
//  * rules are lowercased and converted to ASCII (IDNA/punycode), keeping a leading "*." or "!";
//  * duplicates are removed; the original order is kept.
import { createHash } from 'node:crypto';
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { domainToASCII, fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));

export function normaliseRules(text) {
  const out = [];
  const seen = new Set();
  let section = null;
  const counts = { icann: 0, private: 0 };
  for (const raw of text.split(/\r?\n/)) {
    const line = raw.trim();
    if (line.includes('===BEGIN ICANN DOMAINS===')) section = 'icann';
    else if (line.includes('===BEGIN PRIVATE DOMAINS===')) section = 'private';
    else if (line.includes('===END ICANN DOMAINS===') || line.includes('===END PRIVATE DOMAINS===')) section = null;
    if (!line || line.startsWith('//') || !section) continue;
    const token = line.split(/\s+/)[0].toLowerCase();
    const prefix = token.startsWith('!') ? '!' : token.startsWith('*.') ? '*.' : '';
    const ascii = domainToASCII(token.slice(prefix.length));
    if (!ascii) throw new Error(`cannot convert rule ${JSON.stringify(token)}`);
    const rule = prefix + ascii;
    if (seen.has(rule)) continue;
    seen.add(rule);
    out.push(rule);
    counts[section]++;
  }
  if (counts.icann < 5000 || counts.private < 1000) throw new Error(`unexpected rule counts ${JSON.stringify(counts)}`);
  return { rules: out, counts };
}

function main() {
  const [src, date] = process.argv.slice(2).filter((a) => a !== '--write');
  if (!src || !/^\d{4}-\d{2}-\d{2}$/.test(date || '')) {
    console.error('usage: node gen-psl.mjs <public_suffix_list.dat> <YYYY-MM-DD> --write');
    process.exit(2);
  }
  const bytes = readFileSync(src);
  const sha = createHash('sha256').update(bytes).digest('hex');
  const { rules, counts } = normaliseRules(bytes.toString('utf8'));
  for (const r of rules) if (!/^(\*\.|!)?[a-z0-9-]+(\.[a-z0-9-]+)*$/.test(r)) throw new Error(`unexpected rule ${r}`);
  const body = `// GENERATED by web/tests/vault/gen-psl.mjs — do not edit. Public Suffix List snapshot for \`domain\` URI matching
// (VAULT-CRYPTO.md §3.1): ICANN + PRIVATE sections, lowercase ASCII (punycode) rules, one per line, "*." wildcard and
// "!" exception prefixes kept. Source: https://publicsuffix.org/list/public_suffix_list.dat (snapshot ${date},
// sha256 ${sha}; ${counts.icann} ICANN + ${counts.private} private rules).
// The Public Suffix List is subject to the Mozilla Public License, v. 2.0: https://mozilla.org/MPL/2.0/
export const PSL_DATE = '${date}';
export const PSL_SOURCE_SHA256 = '${sha}';
export const PSL_RULES = \`
${rules.join('\n')}
\`;
`;
  const out = join(here, '..', '..', 'assets', 'js', 'lib', 'vault', 'psl-data.js');
  if (process.argv.includes('--write')) writeFileSync(out, body);
  console.log(`${rules.length} rules (${counts.icann} ICANN, ${counts.private} private), sha256 ${sha}${process.argv.includes('--write') ? ` → ${out}` : ''}`);
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main();
